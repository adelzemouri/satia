const BY_SLUG = new Map(CATALOG.map((recipe) => [recipe.slug, recipe]));

export function catalogRecipe(slug: string): CatalogRecipe | undefined {
  return BY_SLUG.get(slug);
}

/** Recette du catalogue correspondant à un aliment (`source_ref` = `catalog:<slug>`). */
export function catalogRecipeFor(sourceRef: string | null): CatalogRecipe | undefined {
  return sourceRef?.startsWith(CATALOG_PREFIX) ? BY_SLUG.get(sourceRef.slice(CATALOG_PREFIX.length)) : undefined;
}

/**
 * Quelques recettes du catalogue adaptées à un repas, différentes chaque jour (la graine
 * contient la date) mais stables dans la journée.
 */
export function ideasForSlot<T extends { recipe: CatalogRecipe }>(
  entries: readonly T[],
  slot: MealSlot,
  seed: string,
  count: number,
): T[] {
  const random = seededRandom(seed);
  return entries
    .filter((entry) => CATEGORY_SLOTS[entry.recipe.category].includes(slot))
    .map((entry) => ({ entry, rank: random() }))
    .sort((a, b) => a.rank - b.rank)
    .slice(0, count)
    .map(({ entry }) => entry);
}
