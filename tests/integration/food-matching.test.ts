describe("banc d'essai de la saisie IA", () => {
  it("soumet le bon aliment Ciqual à l'IA pour les noms courants", async () => {
    const userId = "00000000-0000-0000-0000-000000000000";
    const missing: string[] = [];
    for (const [label, food] of EXPECTED) {
      const { candidates } = await foodCandidates(userId, label);
      if (!candidates.some((candidate) => food.test(candidate.nameFr))) {
        missing.push(`${label} → ${candidates.map((candidate) => candidate.nameFr).join(" | ")}`);
      }
    }
    expect(missing).toEqual([]);
  }, 60_000);
});
